"""Regenerates src/ui/LogoImage.cpp from resources/logo/xythos-mark.png and xythos-wordmark.png.

The logo in the top bar: the crop circle, glowing, left of the wordmark (the owner's pick, 2026-10-29). Its master is
resources/logo/xythos.svg; tools/render_logo.js renders it in two layers of the same size (the glows are SVG filters,
so it takes a browser): the crop circle in white, which the UI tints with the highlight colour (owner, 2026-10-30;
it was fixed violet), and the letters. Each is embedded as a lossless WebP (decoded with libwebp,
src/ui/WebpImage.*), alpha and all.

Needs Pillow. Run from the repository root after rendering the logo: python3 tools/embed_logo.py
"""
import io
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
LAYERS = [("kLogoMark", ROOT / "resources" / "logo" / "xythos-mark.png"),
          ("kLogoWordmark", ROOT / "resources" / "logo" / "xythos-wordmark.png")]
OUT = ROOT / "src" / "ui" / "LogoImage.cpp"

lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_logo.py from resources/logo/ - do not edit by hand.",
    "",
    '#include "LogoImage.hpp"',
    "",
    "namespace xythos {",
]
for name, source in LAYERS:
    img = Image.open(source).convert("RGBA")
    buf = io.BytesIO()
    img.save(buf, "WEBP", lossless=True, quality=100, method=6, exact=True)
    data = buf.getvalue()
    lines += ["", "const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
    lines += ["};", "const unsigned int %sSize = sizeof(%s);" % (name, name)]
    print("%s: %dx%d, %d bytes" % (source.relative_to(ROOT), img.width, img.height, len(data)))
lines += ["", "} // namespace xythos", ""]
OUT.write_text("\n".join(lines))
