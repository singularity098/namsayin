"""Regenerates src/ui/LogoImage.cpp from resources/logo/xythos.png.

The logo in the top bar: the crop circle, glowing violet, left of the wordmark (the owner's pick, 2026-10-29). Its
master is resources/logo/xythos.svg; tools/render_logo.js renders it to xythos.png (the glows are SVG filters, so it
takes a browser). Embedded as a lossless WebP (decoded with libwebp, src/ui/WebpImage.*), alpha and all.

Needs Pillow. Run from the repository root after rendering the logo: python3 tools/embed_logo.py
"""
import io
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "logo" / "xythos.png"
OUT = ROOT / "src" / "ui" / "LogoImage.cpp"

img = Image.open(SOURCE).convert("RGBA")
buf = io.BytesIO()
img.save(buf, "WEBP", lossless=True, quality=100, method=6, exact=True)
data = buf.getvalue()

lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_logo.py from %s - do not edit by hand." % SOURCE.relative_to(ROOT).as_posix(),
    "",
    '#include "LogoImage.hpp"',
    "",
    "namespace xythos {",
    "",
    "const unsigned char kLogoImage[] = {",
]
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
lines += ["};", "", "const unsigned int kLogoImageSize = sizeof(kLogoImage);", "", "} // namespace xythos", ""]
OUT.write_text("\n".join(lines))
print("%s: %dx%d, %d bytes" % (OUT.relative_to(ROOT), img.width, img.height, len(data)))
