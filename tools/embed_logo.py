"""Makes the UI logo from resources/logo/logo.png and regenerates src/ui/LogoImage.cpp.

The source logo is purple on an opaque black background. For the UI, black becomes transparent (alpha from the
brightest channel, colors un-premultiplied), the faint dark backdrop is dropped, the image is cropped to the logo and
scaled to 96 px high (2x the top bar's logo height), and saved as resources/logo/logo-ui.png (8-bit RGBA, which DPF's
stb_image can decode). The PNG bytes are embedded in the plugin.

Needs Pillow. Run from the repository root after changing the logo: python3 tools/embed_logo.py
"""
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "logo" / "logo.png"
UI_PNG = ROOT / "resources" / "logo" / "logo-ui.png"
OUT = ROOT / "src" / "ui" / "LogoImage.cpp"
HEIGHT = 96
FLOOR = 48  # brightest-channel values up to this are the dark backdrop: fully transparent

src = Image.open(SOURCE).convert("RGB")
out = Image.new("RGBA", src.size)
pixels = []
raw = src.tobytes()
for i in range(0, len(raw), 3):
    r, g, b = raw[i], raw[i + 1], raw[i + 2]
    m = max(r, g, b)
    if m <= FLOOR:
        pixels.append((0, 0, 0, 0))
        continue
    a = min(255, round((m - FLOOR) * 255 / (255 - FLOOR) * 1.6))
    k = 255 / m
    pixels.append((min(255, round(r * k)), min(255, round(g * k)), min(255, round(b * k)), a))
out.putdata(pixels)
out = out.crop(out.getbbox())
out = out.resize((round(out.width * HEIGHT / out.height), HEIGHT), Image.LANCZOS)
out.save(UI_PNG, optimize=True)

data = UI_PNG.read_bytes()
lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_logo.py from resources/logo/ - do not edit by hand.",
    "",
    '#include "LogoImage.hpp"',
    "",
    "namespace namsayin {",
    "",
    "const unsigned char kLogoPng[] = {",
]
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
lines += [
    "};",
    "",
    "const unsigned int kLogoPngSize = sizeof(kLogoPng);",
    "const int kLogoWidth = %d;" % out.width,
    "const int kLogoHeight = %d;" % out.height,
    "",
    "} // namespace namsayin",
    "",
]
OUT.write_text("\n".join(lines))
print("%s: %dx%d, %d bytes" % (UI_PNG.relative_to(ROOT), out.width, out.height, len(data)))
