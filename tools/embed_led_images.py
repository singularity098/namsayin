"""Regenerates src/ui/LedImages.cpp from resources/leds/.

The LEDs on pedal faces are photos (made with Krea-2), in layers:
  off.png    the unlit LED in its chrome bezel, the bezel's circle 0.963 of the image's half-width, the lens 0.672
  lens.png   the lens lit from within, on black, the lit circle 0.955 of the half-width
  bloom.png  the light's halo, on black, its bright core 0.264 of the half-width
  glass.png  the dome's reflections, on black, the dome 0.94 of the half-width
The UI draws the off LED, and while it's lit adds the lens, the bloom and the glass over it.

The photos are hot pink, and an LED can be any colour, so each layer is split into a neutral part and a colour part:
for a pixel, the neutral part is its smallest channel and the colour part what's left over (its largest channel minus
its smallest). Both are embedded as greys; the UI draws the neutral part as is and adds the colour part tinted with
the LED's colour, which turns the pink into that colour while keeping the white-hot centre and the chrome.
Each is cropped so its circle is at a fixed place (the UI's constants in drawFaceLed() rely on them):
  off      the bezel fills the image, the lens is kLensFraction (0.70) of it
  lens     the lit circle fills 0.9 of the image
  bloom    the core is 0.25 of the image, blurred (its lens-flare ring read as a hoop), fading out before the edges
  glass    the dome fills the image

Needs Pillow and NumPy. Run from the repository root after changing the images: python3 tools/embed_led_images.py
"""
import io
import pathlib

import numpy as np
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "leds"
OUT = ROOT / "src" / "ui" / "LedImages.cpp"
SIZE = 128  # face LEDs are at most ~20 logical px across (the bloom ~4x that), so this covers 2x scaling


def load(name, circle, target, blur=0.0):
    """The image, cropped around its centre so that `circle` (a fraction of its half-width) lands at `target`"""
    img = Image.open(SOURCE / name).convert("RGB")
    half = img.width / 2 * circle / target
    c = img.width / 2
    box = (round(c - half), round(c - half), round(c + half), round(c + half))
    img = img.crop(box).resize((SIZE, SIZE), Image.LANCZOS)
    if blur > 0.0:
        img = img.filter(ImageFilter.GaussianBlur(blur))
    return np.asarray(img).astype(np.float64)


def radius():
    """Each pixel's distance from the centre, as a fraction of the half-width"""
    c = (SIZE - 1) / 2
    y, x = np.mgrid[0:SIZE, 0:SIZE]
    return np.hypot(x - c, y - c) / (SIZE / 2)


def split(rgb):
    """The neutral part (smallest channel) and the colour part (largest minus smallest)"""
    lo = rgb.min(axis=2)
    return lo, rgb.max(axis=2) - lo


r = radius()
disc = np.clip((1.0 - r) * SIZE / 2 - 0.5, 0.0, 1.0)  # antialiased disc filling the image

off_neutral, off_colour = split(load("off.png", 0.963, 1.0))
lens_neutral, lens_colour = split(load("lens.png", 0.955, 0.9))
bloom = load("bloom.png", 0.264, 0.25, 4.0) * np.clip((1.0 - r) / 0.3, 0.0, 1.0)[..., None] ** 2
bloom_neutral, bloom_colour = split(bloom)
glass = load("glass.png", 0.94, 1.0).max(axis=2) * disc

layers = [
    # name, function, pixels, mode
    ("kOffPng", "ledOffImage", np.dstack([off_neutral, disc * 255]), "LA"),
    ("kOffColourPng", "ledOffColourImage", off_colour * disc, "L"),
    ("kLensPng", "ledLensImage", lens_neutral, "L"),
    ("kLensColourPng", "ledLensColourImage", lens_colour, "L"),
    ("kBloomPng", "ledBloomImage", bloom_neutral, "L"),
    ("kBloomColourPng", "ledBloomColourImage", bloom_colour, "L"),
    ("kGlassPng", "ledGlassImage", glass, "L"),
]

lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_led_images.py from resources/leds/ - do not edit by hand.",
    "",
    '#include "LedImages.hpp"',
    "",
    "namespace xythos {",
    "",
    "namespace {",
    "",
]
for name, _, pixels, mode in layers:
    buf = io.BytesIO()
    Image.fromarray(np.round(np.clip(pixels, 0, 255)).astype(np.uint8), mode).save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    lines.append("const unsigned char %s[] = {" % name)
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
    lines += ["};", ""]
    print("%s: %dx%d %s, %d bytes" % (name, SIZE, SIZE, mode, len(data)))

lines += ["} // namespace", ""]
for name, function, _, _ in layers:
    lines += ["BuiltinImage %s() { return { %s, sizeof(%s) }; }" % (function, name, name), ""]
lines += ["} // namespace xythos", ""]
OUT.write_text("\n".join(lines))
