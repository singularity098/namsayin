"""Regenerates src/ui/BlockImages.cpp from resources/blocks/.

Each image there is named after a block typeId (doppelganger.png is the Doppelganger Delay's pedal). It's scaled to
at most HEIGHT px high and embedded as an 8-bit RGBA PNG (which DPF's stb_image can decode). The UI shows it for blocks
of that type that have no sidecar image of their own.

Needs Pillow. Run from the repository root after changing the images: python3 tools/embed_block_images.py
"""
import io
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "resources" / "blocks"
OUT = ROOT / "src" / "ui" / "BlockImages.cpp"
HEIGHT = 480  # the block panel image is at most ~240 logical px, so this covers 2x scaling

lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_block_images.py from resources/blocks/ - do not edit by hand.",
    "",
    '#include "BlockImages.hpp"',
    "",
    "#include <cstring>",
    "",
    "namespace namsayin {",
    "",
    "namespace {",
    "",
]
entries = []
for path in sorted(p for p in (SOURCE.iterdir() if SOURCE.is_dir() else []) if p.suffix.lower() in (".png", ".jpg", ".jpeg", ".webp")):
    img = Image.open(path).convert("RGBA")
    if img.height > HEIGHT:
        img = img.resize((round(img.width * HEIGHT / img.height), HEIGHT), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    data = buf.getvalue()
    name = "k" + "".join(c if c.isalnum() else "_" for c in path.stem) + "Png"
    lines.append("const unsigned char %s[] = {" % name)
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
    lines += ["};", ""]
    entries.append((path.stem, name))
    print("%s: %dx%d, %d bytes" % (path.relative_to(ROOT), img.width, img.height, len(data)))

lines += [
    "} // namespace",
    "",
    "BuiltinImage builtinBlockImage(const char* %s)" % ("typeId" if entries else "/*typeId*/"),
    "{",
]
for stem, name in entries:
    lines += [
        '    if (std::strcmp(typeId, "%s") == 0)' % stem,
        "        return { %s, sizeof(%s) };" % (name, name),
    ]
lines += [
    "    return { nullptr, 0 };",
    "}",
    "",
    "} // namespace namsayin",
    "",
]
OUT.write_text("\n".join(lines))
