"""Regenerates src/ui/BackgroundImage.cpp from resources/background/background.*.

The window background behind every panel (the owner's image; the panels over it are translucent black). It's embedded
as a WebP (decoded with libwebp, src/ui/WebpImage.*): a WebP at most WIDTH px wide byte for byte, anything else
re-encoded losslessly (the owner saw compression artifacts in the dark gradients; it must have none).

Needs Pillow. Run from the repository root after changing the image: python3 tools/embed_background.py
"""
import io
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = next((ROOT / "resources" / "background").glob("background.*"))
OUT = ROOT / "src" / "ui" / "BackgroundImage.cpp"
WIDTH = 2000

img = Image.open(SOURCE)
if img.format == "WEBP" and img.width <= WIDTH:
    data = SOURCE.read_bytes()
else:
    img = img.convert("RGB")
    if img.width > WIDTH:
        img = img.resize((WIDTH, round(img.height * WIDTH / img.width)), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", lossless=True, quality=100, method=6)
    data = buf.getvalue()

lines = [
    "// SPDX-License-Identifier: MIT",
    "// Copyright (c) 2026 singularity098",
    "",
    "// Generated by tools/embed_background.py from %s - do not edit by hand." % SOURCE.relative_to(ROOT).as_posix(),
    "",
    '#include "BackgroundImage.hpp"',
    "",
    "namespace xythos {",
    "",
    "const unsigned char kBackgroundImage[] = {",
]
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
lines += ["};", "", "const unsigned int kBackgroundImageSize = sizeof(kBackgroundImage);", "", "} // namespace xythos", ""]
OUT.write_text("\n".join(lines))
print("%s: %dx%d, %d bytes" % (OUT.relative_to(ROOT), img.width, img.height, len(data)))
